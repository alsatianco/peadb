constexpr const char* kSignature = "# Generated by CONFIG REWRITE";

// sdscatrepr(): quote config arguments, including binary SDS values, so our own
// sdssplitargs-compatible loader can read every byte back.
std::string quote_argument(std::string_view value) {
  constexpr char hex[] = "0123456789abcdef";
  std::string out = "\"";
  for (unsigned char c : value) {
    switch (c) {
      case '\\':
        out += "\\\\";
        break;
      case '"':
        out += "\\\"";
        break;
      case '\n':
        out += "\\n";
        break;
      case '\r':
        out += "\\r";
        break;
      case '\t':
        out += "\\t";
        break;
      case '\a':
        out += "\\a";
        break;
      case '\b':
        out += "\\b";
        break;
      default:
        if (c >= 32 && c <= 126) {
          out += static_cast<char>(c);
        } else {
          out += "\\x";
          out += hex[c >> 4];
          out += hex[c & 15];
        }
    }
  }
  return out + '"';
}

std::string memory_value(const std::string& value) {
  unsigned long long bytes = 0;
  const auto result = std::from_chars(value.data(), value.data() + value.size(), bytes);
  if (result.ec != std::errc() || result.ptr != value.data() + value.size() || bytes == 0)
    return value;
  for (const auto& [unit, suffix] : {std::pair{1024ULL * 1024 * 1024, "gb"},
                                     std::pair{1024ULL * 1024, "mb"}, std::pair{1024ULL, "kb"}}) {
    if (bytes % unit == 0) return std::to_string(bytes / unit) + suffix;
  }
  return value;
}

struct RewriteState {
  std::vector<std::string> lines;
  std::unordered_map<std::string, std::deque<std::size_t>> positions;
  std::unordered_set<std::string> processed;
  bool needs_signature = true;

  void write(const std::string& name, std::string line, bool force) {
    processed.insert(name);
    auto it = positions.find(name);
    if (it != positions.end() && !it->second.empty()) {
      lines[it->second.front()] = std::move(line);
      it->second.pop_front();
    } else if (force) {
      if (needs_signature) {
        lines.emplace_back(kSignature);
        needs_signature = false;
      }
      lines.push_back(std::move(line));
    }
  }

  std::string content() {
    for (const auto& [name, remaining] : positions) {
      if (processed.count(name) == 0) continue;
      for (const auto line : remaining) lines[line].clear();
    }
    std::string result;
    bool was_empty = false;
    for (const auto& line : lines) {
      if (line.empty() && was_empty) continue;
      was_empty = line.empty();
      result += line;
      result += '\n';
    }
    return result;
  }
};

bool read_old_file(const std::string& path, RewriteState& state) {
  FILE* file = std::fopen(path.c_str(), "r");
  if (file == nullptr) return errno == ENOENT;
  struct stat st {};
  if (::fstat(fileno(file), &st) == -1) {
    const int error = errno;
    std::fclose(file);
    errno = error;
    return false;
  }
  std::string text(static_cast<std::size_t>(st.st_size), '\0');
  const auto count = text.empty() ? 0 : std::fread(text.data(), 1, text.size(), file);
  const bool failed = count != text.size();
  const int error = std::ferror(file) ? errno : EIO;
  std::fclose(file);
  if (failed) {
    errno = error != 0 ? error : EIO;
    return false;
  }
  if (text.empty()) return true;
  std::size_t start = 0;
  while (true) {
    const auto end = text.find('\n', start);
    std::string line = text.substr(start, end == std::string::npos ? end : end - start);
    const auto first = line.find_first_not_of("\r\n\t ");
    if (first == std::string::npos)
      line.clear();
    else
      line = line.substr(first, line.find_last_not_of("\r\n\t ") - first + 1);
    if (line == kSignature) state.needs_signature = false;
    if (!line.empty() && line[0] != '#') {
      std::vector<std::string> args;
      const bool valid = split_config_args(line, args) && !args.empty();
      const RedisConfigSpec* spec = valid ? find_redis_config(args[0]) : nullptr;
      std::string name = valid ? args[0] : std::string();
      for (char& c : name)
        if (c >= 'A' && c <= 'Z') c += 'a' - 'A';
      if (spec != nullptr) name = spec->name;
      if (!valid || (spec == nullptr && name != "include" && name != "rename-command" &&
                     name != "user" && name != "loadmodule" && name != "sentinel")) {
        line = "# ??? " + line;
      } else {
        state.positions[name].push_back(state.lines.size());
      }
    }
    state.lines.push_back(std::move(line));
    if (end == std::string::npos) break;
    start = end + 1;
  }
  return true;
}

void rewrite_option(RewriteState& state, const RedisConfigSpec& spec, std::string value,
                    bool replica, const std::string& replica_host, int replica_port) {
  const std::string name = spec.name;
  const bool force = spec.default_value == nullptr || value != spec.default_value;
  if (spec.type == RedisConfigType::String) {
    if (!spec.string_sds)
      value.resize(value.find('\0') == std::string::npos ? value.size() : value.find('\0'));
    if (spec.string_empty_to_null && value.empty()) {
      state.processed.insert(name);
      return;
    }
    const bool string_force = spec.string_null_default || value != spec.default_value;
    state.write(name, name + " " + quote_argument(value), string_force);
  } else if (spec.type == RedisConfigType::Numeric) {
    state.write(name,
                name + " " + ((spec.numeric_flags & kNumMemory) != 0 ? memory_value(value) : value),
                force);
  } else if (spec.type != RedisConfigType::Special) {
    state.write(name, name + " " + value, force);
  } else if (name == "save") {
    const auto args = config_set_args(spec, value);
    if (args.empty()) state.write(name, "save \"\"", true);
    for (std::size_t i = 0; i + 1 < args.size(); i += 2)
      state.write(name, name + " " + args[i] + " " + args[i + 1], true);
    state.processed.insert(name);
  } else if (name == "client-output-buffer-limit") {
    const auto args = config_set_args(spec, value);
    const auto defaults = config_set_args(spec, spec.default_value);
    for (std::size_t i = 0; i + 3 < args.size(); i += 4) {
      bool changed = false;
      for (std::size_t j = 1; j < 4; ++j) changed |= args[i + j] != defaults[i + j];
      const auto cls = args[i] == "slave" ? "replica" : args[i];
      state.write(name,
                  name + " " + cls + " " + memory_value(args[i + 1]) + " " +
                      memory_value(args[i + 2]) + " " + args[i + 3],
                  changed);
    }
  } else if (name == "replicaof") {
    state.processed.insert(name);
    if (replica)
      state.write(name,
                  name + " " + quote_argument(replica_host) + " " + std::to_string(replica_port),
                  true);
  } else if (name == "dir") {
    state.processed.insert(name);
    if (!value.empty()) state.write(name, name + " " + quote_argument(value), true);
  } else if (name == "notify-keyspace-events") {
    state.write(name, name + " " + quote_argument(value), !value.empty());
  } else if (name == "bind") {
    state.processed.insert(name);
    if (force) state.write(name, name + " " + (value.empty() ? "\"\"" : value), true);
  } else if (name == "latency-tracking-info-percentiles") {
    state.write(name, name + " " + (value.empty() ? "\"\"" : value), true);
  } else if (name == "oom-score-adj-values") {
    state.write(name, name + " " + value, force);
  }
}

bool sync_directory(const std::string& path) {
  auto parent = std::filesystem::path(path).parent_path();
  if (parent.empty()) parent = ".";
  const int fd = ::open(parent.c_str(), O_RDONLY);
  if (fd == -1) return errno == EISDIR;

    // Redis's fsyncFileDir uses redis_fsync, whose native operation differs from
    // the plain fsync used for the temporary config file itself.
#if defined(__linux__)
  const int rc = ::fdatasync(fd);
#elif defined(__APPLE__)
  const int rc = ::fcntl(fd, F_FULLFSYNC);
#else
  const int rc = ::fsync(fd);
#endif
  const int error = errno;
  ::close(fd);
  errno = error;
  return rc == 0 || error == EBADF || error == EINVAL;
}

bool publish(const std::string& path, const std::string& content, mode_t startup_umask) {
  if (path.size() + 7 >= PATH_MAX) {
    errno = ENAMETOOLONG;
    return false;
  }
  std::string temp = path + ".XXXXXX";
#if defined(_GNU_SOURCE) && !defined(__HAIKU__)
  const int fd = ::mkostemp(temp.data(), O_CLOEXEC);
#else
  const int fd = ::mkstemp(temp.data());
#endif
  if (fd == -1) return false;
  std::size_t offset = 0;
  bool ok = true;
  while (offset < content.size()) {
    const auto written = ::write(fd, content.data() + offset, content.size() - offset);
    if (written < 0 && errno == EINTR) continue;
    if (written <= 0) {
      if (written == 0) errno = EIO;
      ok = false;
      break;
    }
    offset += static_cast<std::size_t>(written);
  }
  ok = ok && ::fsync(fd) == 0 && ::fchmod(fd, 0644 & ~startup_umask) == 0 &&
       ::rename(temp.c_str(), path.c_str()) == 0 && sync_directory(path);
  const int error = errno;
  ::close(fd);
  if (!ok) ::unlink(temp.c_str());
  errno = error;
  return ok;
}

