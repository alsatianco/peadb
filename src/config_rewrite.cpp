bool rewrite_config_file(const std::string& path,
                         const std::function<std::string(const RedisConfigSpec&)>& value,
                         bool replica, const std::string& replica_host, int replica_port,
                         mode_t startup_umask) {
  RewriteState state;
  if (!read_old_file(path, state)) return false;
  for (const auto& spec : kRedisConfigSpecs)
    rewrite_option(state, spec, value(spec), replica, replica_host, replica_port);
  // PeaDB has only the default user, represented losslessly by requirepass. Do not
  // generate Redis's ACL user lines: the loader deliberately refuses ACL features.
  // Existing user/module directives remain intact and retain that startup refusal.
  return publish(path, state.content(), startup_umask);
}

