#!/usr/bin/env python3
"""
generate_compat_scoreboard.py — Generates compat/commands.generated.md

Parses the command table in src/command.cpp to extract all registered
commands, cross-references them against integration tests to determine
coverage level, then writes compat/commands.generated.md.

Coverage levels (per compat/delta.md definition):
  full     — integration test + differential test
  partial  — integration test only
  surface  — command name mentioned in test file but not invoked as a call
  stub     — no test coverage
"""

import re
import sys
import os
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
COMMAND_CPP = REPO_ROOT / "src" / "command.cpp"
TESTS_DIR = REPO_ROOT / "tests" / "integration"
OUT_FILE = REPO_ROOT / "compat" / "commands.generated.md"

# Commands that have explicit differential/compat tests
DIFFERENTIAL_COMMANDS: set[str] = set()

def extract_commands(cpp_path: Path) -> list[str]:
    """Extract command names from t.emplace("NAME", ...) calls."""
    text = cpp_path.read_text()
    return sorted(set(re.findall(r't\.emplace\("([A-Z0-9_]+)"', text)))

def test_invocations(tests_dir: Path) -> dict[str, set[str]]:
    """
    For each command, find which test files contain a redis client call
    that invokes it (not just a mention in a string or comment).
    """
    result: dict[str, set[str]] = {}
    if not tests_dir.exists():
        return result
    for test_file in sorted(tests_dir.glob("test_*.py")):
        text = test_file.read_text(errors="replace")
        # Look for r.COMMAND(...) or r.execute_command("COMMAND", ...) patterns
        for m in re.finditer(r'r\.([A-Z][A-Z0-9_]*)\(', text):
            cmd = m.group(1).upper()
            result.setdefault(cmd, set()).add(test_file.name)
        for m in re.finditer(r'execute_command\(["\']([A-Z][A-Z0-9_]+)', text, re.IGNORECASE):
            cmd = m.group(1).upper()
            result.setdefault(cmd, set()).add(test_file.name)
        for m in re.finditer(r'r\.execute\(["\']([A-Z][A-Z0-9_]+)', text, re.IGNORECASE):
            cmd = m.group(1).upper()
            result.setdefault(cmd, set()).add(test_file.name)
    return result

def coverage_level(cmd: str, invocations: dict[str, set[str]]) -> str:
    if cmd in DIFFERENTIAL_COMMANDS:
        return "full"
    if cmd in invocations and invocations[cmd]:
        return "partial"
    return "stub"

def main() -> None:
    if not COMMAND_CPP.exists():
        print(f"ERROR: {COMMAND_CPP} not found", file=sys.stderr)
        sys.exit(1)

    commands = extract_commands(COMMAND_CPP)
    invocations = test_invocations(TESTS_DIR)

    counts = {"full": 0, "partial": 0, "stub": 0}
    rows: list[tuple[str, str, str]] = []
    for cmd in commands:
        level = coverage_level(cmd, invocations)
        tests = ", ".join(sorted(invocations.get(cmd, set()))) or "—"
        rows.append((cmd, level, tests))
        counts[level] += 1

    lines = [
        "# Commands Compatibility Scoreboard",
        "",
        f"> Auto-generated by `scripts/ci/generate_compat_scoreboard.py`. Do not edit manually.",
        "",
        f"Total: **{len(commands)}** commands — "
        f"full: {counts['full']}, partial: {counts['partial']}, stub: {counts['stub']}",
        "",
        "| Command | Coverage | Test files |",
        "|---------|----------|------------|",
    ]
    for cmd, level, tests in rows:
        lines.append(f"| `{cmd}` | {level} | {tests} |")

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text("\n".join(lines) + "\n")
    print(f"Written {OUT_FILE} ({len(commands)} commands)")

if __name__ == "__main__":
    main()
